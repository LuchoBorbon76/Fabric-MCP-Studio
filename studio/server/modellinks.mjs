// What is built around a semantic model/workspace in Fabric – reports, data agents, ontologies, plans, real-time items –
// and the data it reads. Found when an existing model is added (or on request) so the map shows the whole picture. Read
// only: the studio never changes or deletes these items, they stay the user's. A project without data takes the model's
// data in place (nothing is copied).
import * as F from './fabric.mjs';
import { workspaceReports } from './powerbi.mjs';
import { decodeText } from './reports/zip.mjs';
import { reportUrl } from './reports/index.mjs';
import { allThemes } from './reports/themes.mjs';
import { listTemplates } from './reports/library.mjs';
import { getProject, updateProject, logActivity, assertProjectTenant, projectModels, modelWorkspaceId, fabricUrl, contextViews } from './project.mjs';
import { startJob, listJobs } from './jobs.mjs';
import { isNetworkError } from './config.mjs';
import { modelSourceItems } from './modelcheck.mjs';
import { adoptModelSource } from './pipelines.mjs';
import { parseName } from './naming.mjs';

// Version of what a look in Fabric finds; a model looked at by an older version is looked at again (2: reports the
// studio built are recognised by their description).
export const LINKS_VERSION = 3;
// Reading a data agent's definition takes Fabric about 20 seconds: a few at a time, and not without end.
const AGENTS_AT_ONCE = 4;
const MAX_AGENTS = 30;
const firstLine = (e) => String(e?.message || e).split('\n')[0].slice(0, 200);
const stdMatch = (item, codes, p = getProject()) => {
  const x = parseName(item.displayName || item.name || '');
  return x && codes.includes(x.code) && (!p.naming?.domain || x.domain.toLowerCase() === p.naming.domain.toLowerCase()) && (!p.naming?.environment || x.environment.toLowerCase() === p.naming.environment.toLowerCase());
};
const newest = (items) => items.sort((a, b) => String(b.modifiedDateTime || b.createdDateTime || '').localeCompare(String(a.modifiedDateTime || a.createdDateTime || '')))[0] || null;
const decodePartText = (part) => decodeText(Buffer.from(part.payload || '', 'base64'));

async function inBatches(list, n, fn) {
  const out = [];
  for (let i = 0; i < list.length; i += n) out.push(...await Promise.all(list.slice(i, i + n).map(fn)));
  return out;
}

// The description every report the studio builds gets ("Power BI report generated by Fabric MCP Studio from …", or
// "… from the template X, built by Fabric MCP Studio on …").
const STUDIO_REPORT = /^Power BI report (generated by Fabric MCP Studio|from the template .+, built by Fabric MCP Studio)/i;

/** Power BI reports (in the given workspaces) whose dataset is the model; `studio` marks the ones the studio built. */
async function reportsOn(model, workspaces, notes) {
  const found = [];
  for (const ws of workspaces) {
    let list;
    try { list = await workspaceReports(ws); } catch (e) { notes.push(`Reports couldn't be listed in a workspace (${firstLine(e)}).`); continue; }
    // Fabric's item list has the descriptions (the Power BI list doesn't).
    const described = new Map((await F.listItems(ws, 'Report').catch(() => [])).map((i) => [i.id, i.description || '']));
    for (const r of list) {
      if (r.datasetId !== model.id || found.some((x) => x.id === r.id)) continue;
      const url = r.type === 'PaginatedReport' ? `https://app.powerbi.com/groups/${ws}/rdlreports/${r.id}` : reportUrl(ws, r.id);
      const description = described.get(r.id) || '';
      found.push({ id: r.id, name: r.name, workspaceId: ws, type: r.type, url, ...(STUDIO_REPORT.test(description) ? { studio: true, description } : {}) });
    }
  }
  return found;
}

/** Theme and page names of a report the studio built, read from its definition (null when it can't be read). */
async function studioReportDesign(r) {
  let parts;
  try { parts = (await F.getDefinition(r.workspaceId, r.id))?.parts || []; } catch { return null; }
  const json = (path) => { const x = parts.find((p) => p.path === path); try { return x ? JSON.parse(decodeText(Buffer.from(x.payload || '', 'base64'))) : null; } catch { return null; } };
  const themeFile = json('definition/report.json')?.themeCollection?.customTheme?.name || '';
  const theme = allThemes().find((t) => `FabricStudio-${t.id.replace(/[^A-Za-z0-9_-]/g, '-')}.json` === themeFile)?.id || null;
  const order = json('definition/pages/pages.json')?.pageOrder || [];
  const pages = order.map((name) => json(`definition/pages/${name}/page.json`)?.displayName).filter(Boolean);
  return { theme, pages };
}

/**
 * Reports the studio built on the model that the project doesn't list (built by another copy of the studio, or before
 * the project was started over) become the project's own again: they can be rebuilt, removed and put in the org app.
 * Only reports in the project's workspace, and never one another data source of the workspace already has.
 */
async function adoptStudioReports(m, reports, ctx) {
  const p = getProject();
  const known = new Set(contextViews(p).flatMap(({ view }) => (view.reports || []).map((r) => r.id)));
  const candidates = reports.filter((r) => r.studio && r.type !== 'PaginatedReport' && r.workspaceId === p.workspace?.id && !known.has(r.id));
  if (!candidates.length) return [];
  const templates = listTemplates();
  const adopted = [];
  for (const r of candidates) {
    if (ctx.signal?.aborted) break;
    const design = await studioReportDesign(r);
    const tplName = r.description.match(/from the template (.+), built by Fabric MCP Studio/i)?.[1];
    const tpl = tplName ? templates.find((t) => t.kind !== 'theme' && t.name === tplName) : null;
    adopted.push({
      id: r.id, name: r.name, theme: tplName ? null : design?.theme || null, pages: design?.pages || [],
      ...(tpl ? { template: { id: tpl.id, name: tpl.name } } : {}),
      semanticModelId: m.id, url: r.url, builtAt: null, preview: null, adoptedAt: new Date().toISOString(),
    });
  }
  // Read again: the project may have changed while the definitions were read.
  const now = getProject();
  if (now.workspace?.id !== p.workspace?.id || !projectModels(now).some((x) => x.id === m.id)) return [];
  const have = new Set((now.reports || []).map((r) => r.id));
  const add = adopted.filter((r) => !have.has(r.id));
  if (add.length) updateProject({ reports: [...(now.reports || []), ...add] });
  return add;
}

/** Fabric data agents (in the given workspaces) that answer from the model: their definition names the model's id. */
async function agentsOn(model, workspaces, notes, ctx) {
  const items = [];
  for (const ws of workspaces) {
    try { for (const it of await F.listItems(ws, 'DataAgent')) items.push({ ...it, workspaceId: ws }); } catch (e) { notes.push(`Data agents couldn't be listed in a workspace (${firstLine(e)}).`); }
  }
  if (!items.length) return [];
  if (items.length > MAX_AGENTS) notes.push(`Only the first ${MAX_AGENTS} of ${items.length} data agents were checked.`);
  const list = items.slice(0, MAX_AGENTS);
  ctx?.log?.(`Reading ${list.length} data agent${list.length === 1 ? '' : 's'} (about 20 seconds each, ${AGENTS_AT_ONCE} at a time)`);
  const id = model.id.toLowerCase();
  let unreadable = 0;
  let dropped = 0;
  const hits = await inBatches(list, AGENTS_AT_ONCE, async (it) => {
    if (ctx?.signal?.aborted) return null;
    let parts;
    try { parts = (await F.getDefinition(it.workspaceId, it.id))?.parts || []; } catch (e) { if (isNetworkError(e)) dropped++; else unreadable++; return null; }
    const uses = parts.some((p) => /datasource\.json$/i.test(p.path) && decodeText(Buffer.from(p.payload || '', 'base64')).toLowerCase().includes(id));
    if (!uses) return null;
    const published = parts.some((p) => /Files\/Config\/publish_info\.json$/i.test(p.path));
    return { id: it.id, name: it.displayName, workspaceId: it.workspaceId, published, url: fabricUrl('DataAgent', it.workspaceId, it.id) };
  });
  if (unreadable) notes.push(`${unreadable} data agent${unreadable === 1 ? '' : 's'} couldn't be read (reading one needs Contributor access to it).`);
  if (dropped) notes.push(`${dropped} data agent${dropped === 1 ? '' : 's'} couldn't be read because the connection to Fabric dropped – select Look again.`);
  return hits.filter(Boolean);
}

async function definitionContains(workspaceId, item, needles) {
  if (!needles.filter(Boolean).length) return false;
  try {
    const text = ((await F.getDefinition(workspaceId, item.id))?.parts || []).map(decodePartText).join('\n').toLowerCase();
    return needles.filter(Boolean).some((x) => text.includes(String(x).toLowerCase()));
  } catch { return false; }
}

async function adoptWorkspaceArtifacts(model, linked, notes) {
  const p = getProject();
  const ws = p.workspace?.id;
  if (p.semanticModel?.id !== model.id) return { ontology: null, realtime: null, plan: null, taskFlow: null };
  if (!ws) return { ontology: null, realtime: null, plan: null, taskFlow: null };
  const items = await F.listItems(ws).catch((e) => { notes.push(`Workspace items couldn't be listed (${firstLine(e)}).`); return []; });
  const byType = (type) => items.filter((i) => i.type === type);
  const sourceIds = (linked.sources || []).map((s) => s.id).filter(Boolean);
  const sourceNames = (linked.sources || []).map((s) => s.name).filter(Boolean);
  const needles = [model.id, model.name, ...sourceIds, ...sourceNames];
  const patch = {};
  let ontology = null;
  if (!p.ontology) {
    const onts = byType('Ontology').filter((i) => stdMatch(i, ['ONT'], p));
    ontology = (await Promise.all(onts.map(async (i) => ({ item: i, hit: await definitionContains(ws, i, needles) })))).find((x) => x.hit)?.item || (onts.length === 1 ? onts[0] : null);
    if (ontology) patch.ontology = { id: ontology.id, name: ontology.displayName, workspaceId: ws, sourceItemId: sourceIds[0] || null, adoptedAt: new Date().toISOString() };
  }
  if (!p.realtime) {
    const eventhouse = newest(byType('Eventhouse').filter((i) => stdMatch(i, ['EH'], p)));
    const eventstream = newest(byType('Eventstream').filter((i) => stdMatch(i, ['ES'], p)));
    if (eventhouse || eventstream) {
      let queryUri = null;
      let database = null;
      if (eventhouse) {
        try {
          const props = (await F.fabric('GET', `/workspaces/${ws}/eventhouses/${eventhouse.id}`))?.properties || {};
          queryUri = props.queryServiceUri || null;
          const dbs = await F.listItems(ws, 'KQLDatabase').catch(() => []);
          const db = dbs.find((d) => (props.databasesItemIds || []).includes(d.id)) || null;
          if (db) database = { id: db.id, name: db.displayName };
        } catch (e) { notes.push(`Eventhouse "${eventhouse.displayName}" details couldn't be read (${firstLine(e)}).`); }
      }
      const dashboard = newest(byType('KQLDashboard').filter((i) => stdMatch(i, ['RTD'], p)));
      const alerts = newest(byType('Reflex').filter((i) => stdMatch(i, ['ACT'], p)));
      const kq = byType('KQLQueryset').filter((i) => stdMatch(i, ['KQS'], p));
      const silverQueryset = kq.find((i) => /bronze.*silver|silver/i.test(i.displayName)) || null;
      const goldQueryset = kq.find((i) => /silver.*gold|gold/i.test(i.displayName)) || null;
      const goldModel = byType('SemanticModel').find((i) => stdMatch(i, ['SM'], p) && /live|gold/i.test(i.displayName)) || null;
      const silverLakehouse = byType('Lakehouse').find((i) => stdMatch(i, ['LH'], p) && /silver/i.test(i.displayName)) || null;
      patch.realtime = {
        scenario: { id: 'adopted', label: 'Existing live events', table: 'BusinessEvents', columns: [] },
        eventhouse: eventhouse ? { id: eventhouse.id, name: eventhouse.displayName, queryUri } : null,
        database,
        table: 'BusinessEvents',
        eventstream: eventstream ? { id: eventstream.id, name: eventstream.displayName } : null,
        dashboard: dashboard ? { id: dashboard.id, name: dashboard.displayName, url: fabricUrl('KQLDashboard', ws, dashboard.id), pages: [], tiles: null, refreshSeconds: null, adoptedAt: new Date().toISOString() } : null,
        alerts: alerts ? { id: alerts.id, name: alerts.displayName, url: fabricUrl('Reflex', ws, alerts.id), adoptedAt: new Date().toISOString() } : null,
        medallion: (silverQueryset || goldQueryset || goldModel || silverLakehouse) ? {
          adoptedAt: new Date().toISOString(),
          names: { bronze: 'BusinessEvents', silver: 'BusinessEvents_Silver', quarantine: 'BusinessEvents_Quarantine', clean: 'BusinessEvents_Silver_Dedup' },
          items: {
            silverQueryset: silverQueryset ? { id: silverQueryset.id, name: silverQueryset.displayName } : null,
            goldQueryset: goldQueryset ? { id: goldQueryset.id, name: goldQueryset.displayName } : null,
            goldModel: goldModel ? { id: goldModel.id, name: goldModel.displayName } : null,
            silverLakehouse: silverLakehouse ? { id: silverLakehouse.id, name: silverLakehouse.displayName } : null,
          },
        } : null,
        adoptedAt: new Date().toISOString(),
      };
    }
  }
  if (!p.planning?.planItem) {
    const plan = newest(byType('Plan').filter((i) => stdMatch(i, ['PLAN'], p)));
    if (plan && p.planning) patch.planning = { ...p.planning, planItem: { id: plan.id, name: plan.displayName, url: fabricUrl('Plan', ws, plan.id), connected: false, adoptedAt: new Date().toISOString(), sheetSetup: { required: true, reason: 'Existing Fabric Plan item adopted by the studio; create/connect a Planning Sheet in Fabric.', steps: ['Open the plan', 'Select New Planning Sheet', `Use Data > Add to pick ${model.name}`, 'Select Add, then Connect with your own sign-in'] } } };
  }
  if (!p.taskFlow) {
    const taskFlow = newest(items.filter((i) => ['TaskFlow', 'DataPipeline'].includes(i.type) && stdMatch(i, ['TF'], p)));
    if (taskFlow) patch.taskFlow = { mode: 'existing', id: taskFlow.id, name: taskFlow.displayName, adoptedAt: new Date().toISOString() };
  }
  if (Object.keys(patch).length) updateProject(patch);
  return { ontology: patch.ontology?.name || null, realtime: patch.realtime?.eventhouse?.name || patch.realtime?.eventstream?.name || null, plan: patch.planning?.planItem?.name || null, taskFlow: patch.taskFlow?.name || null };
}

/** Change a project model's entry (the active one through semanticModel, so it stays in step). */
function patchModel(id, patch) {
  const p = getProject();
  const m = (p.semanticModels || []).find((x) => x.id === id);
  if (!m) return false;
  if (p.semanticModel?.id === id) updateProject({ semanticModel: { ...p.semanticModel, ...patch } });
  else updateProject({ semanticModels: p.semanticModels.map((x) => (x.id === id ? { ...x, ...patch } : x)) });
  return true;
}

/**
 * Job: find the reports and data agents built on a project model (the active one by default) and the data it reads, and
 * show them on the map. With `adopt`, a project without data takes the model's data in place.
 */
export async function runModelLinks(ctx, { id, adopt = true } = {}) {
  await assertProjectTenant();
  const p = getProject();
  const m = id ? projectModels(p).find((x) => x.id === id) : p.semanticModel;
  if (!m) throw Object.assign(new Error(id ? 'That semantic model isn\'t in the project.' : 'There is no semantic model yet.'), { status: 404 });
  const ws = modelWorkspaceId(p, m);
  const workspaces = [...new Set([ws, p.workspace?.id].filter(Boolean))];
  const notes = [];
  ctx.step(`Find what is built on ${m.name}`);
  ctx.progress(10);
  // The studio's own models know their data; an existing model's comes from its definition.
  const sourcesP = m.origin === 'existing'
    ? modelSourceItems(ws, m.id).catch((e) => { notes.push(`The model's data couldn't be read from its definition (${firstLine(e)}).`); return null; })
    : Promise.resolve(null);
  const [reports, agents, sources] = await Promise.all([reportsOn(m, workspaces, notes), agentsOn(m, workspaces, notes, ctx), sourcesP]);
  if (ctx.signal?.aborted) throw new Error('Cancelled');
  ctx.progress(80);
  const prev = m.linked || {};
  const linked = { reports, agents, sources: sources ?? prev.sources ?? [], at: new Date().toISOString(), notes, v: LINKS_VERSION };
  if (!patchModel(m.id, { linked })) {
    ctx.log('The semantic model is no longer in the project (another data source or workspace is active): nothing was saved.');
    return { model: m.name, reports: reports.length, agents: agents.length, saved: false };
  }
  const adoptedArtifacts = await adoptWorkspaceArtifacts(m, linked, notes);
  ctx.log(`${reports.length} report${reports.length === 1 ? '' : 's'}${reports.length ? `: ${reports.map((r) => r.name).join(', ')}` : ''}`);
  const back = await adoptStudioReports(m, reports, ctx);
  if (back.length) ctx.log(`Built by the studio, back in the project: ${back.map((r) => r.name).join(', ')} (they can be rebuilt and go in the org app)`);
  for (const [kind, name] of Object.entries(adoptedArtifacts)) if (name) ctx.log(`Existing ${kind} added to the project: ${name}`);
  ctx.log(`${agents.length} data agent${agents.length === 1 ? '' : 's'}${agents.length ? `: ${agents.map((a) => a.name).join(', ')}` : ''}`);
  if (linked.sources.length) ctx.log(`Reads ${linked.sources.map((s) => `${s.name} (${s.type})`).join(', ')}`);
  for (const n of notes) ctx.log(n);

  let adopted = null;
  if (adopt && linked.sources.length === 1 && getProject().semanticModel?.id === m.id) {
    const s = linked.sources[0];
    ctx.step(`Use ${s.name} as the data source`);
    try {
      if (await adoptModelSource({ workspaceId: s.workspaceId, itemId: s.id, itemType: s.type, modelId: m.id }, ctx)) {
        adopted = s;
        ctx.log(`Data source: ${s.name}, used in place (nothing is copied)`);
      }
    } catch (e) { ctx.log(`${s.name} couldn't be used as the data source (${firstLine(e)}). Connect it on the Data page.`); }
  }
  ctx.progress(100);
  const what = [reports.length ? `${reports.length} report${reports.length === 1 ? '' : 's'}` : null, agents.length ? `${agents.length} data agent${agents.length === 1 ? '' : 's'}` : null].filter(Boolean).join(' and ');
  logActivity('model.links', `${m.name}: ${what || 'no reports or data agents'} found in Fabric${back.length ? `; ${back.map((r) => r.name).join(', ')} built by the studio` : ''}${adopted ? `; data source ${adopted.name}` : ''}`, { semanticModelId: m.id, studioReports: back.map((r) => r.id), adoptedArtifacts });
  return { model: m.name, reports: reports.length, agents: agents.length, studioReports: back.map((r) => r.name), sources: linked.sources.map((s) => s.name), adopted: adopted?.name || null, adoptedArtifacts, notes };
}

/** Start looking at a model (or return the search already running for it). */
export function startModelLinks(id) {
  const running = listJobs().find((j) => j.kind === 'model-links' && j.status === 'running' && j.meta?.modelId === id);
  if (running) return running;
  const name = getProject().semanticModels?.find((m) => m.id === id)?.name;
  return startJob('model-links', `Find what is built on ${name || 'the semantic model'}`, (ctx) => runModelLinks(ctx, { id }), { meta: { modelId: id } });
}

/**
 * An existing model that hasn't been looked at yet (or by an older studio, which didn't recognise the reports it built):
 * look in the background. Returns the job id, or null.
 */
export function ensureModelLinks(id) {
  const m = getProject().semanticModels?.find((x) => x.id === id);
  if (!m || m.origin !== 'existing' || (m.linked?.at && m.linked.v >= LINKS_VERSION)) return null;
  return startModelLinks(id).id;
}
